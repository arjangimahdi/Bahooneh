import { describe, expect, it } from "vitest";
import { numberToPersianWords } from "./numberToWords";

describe("numberToPersianWords", () => {
  it.each([
    [0, "صفر"],
    [5, "پنج"],
    [10, "ده"],
    [15, "پانزده"],
    [21, "بیست و یک"],
    [100, "صد"],
    [250, "دویست و پنجاه"],
    [999, "نهصد و نود و نه"],
    [1_000, "هزار"],
    [1_500, "هزار و پانصد"],
    [12_000, "دوازده هزار"],
    [100_000, "صد هزار"],
    [500_000, "پانصد هزار"],
    [1_000_000, "یک میلیون"],
    [1_250_000, "یک میلیون و دویست و پنجاه هزار"],
    [3_000_000, "سه میلیون"],
    [30_000_000, "سی میلیون"],
    [1_000_001, "یک میلیون و یک"],
    [2_001_000, "دو میلیون و هزار"],
    [1_000_000_000, "یک میلیارد"],
  ])("%d → %s", (input, expected) => {
    expect(numberToPersianWords(input)).toBe(expected);
  });
});
